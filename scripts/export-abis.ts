import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const ROOT_DIR = process.cwd();
const ARTIFACTS_DIR = path.join(ROOT_DIR, "artifacts", "contracts");
const DEPLOYMENTS_FILE = path.join(ROOT_DIR, "deployments", "aevum.json");
const OUT_DIR = path.join(ROOT_DIR, "frontend", "src", "lib", "contracts");

const ZERO_ADDRESS = "0x0000000000000000000000000000000000000000";
const DEFAULT_TUSD8 = "0x456569838f1d43009A91ebA4263147Afd7233483";

const CONTRACT_ARTIFACTS = [
  { exportName: "IDENTITY_REGISTRY_ABI", relPath: "registries/IdentityRegistry.sol/IdentityRegistry.json" },
  { exportName: "REPUTATION_REGISTRY_ABI", relPath: "registries/ReputationRegistry.sol/ReputationRegistry.json" },
  { exportName: "VALIDATION_REGISTRY_ABI", relPath: "registries/ValidationRegistry.sol/ValidationRegistry.json" },
  { exportName: "MILESTONE_ESCROW_ABI", relPath: "core/MilestoneEscrow.sol/MilestoneEscrow.json" },
  { exportName: "PROJECT_MANAGER_ABI", relPath: "core/ProjectManager.sol/ProjectManager.json" },
  { exportName: "DISPUTE_RESOLUTION_ABI", relPath: "core/DisputeResolution.sol/DisputeResolution.json" },
  { exportName: "ERC20_ABI", relPath: "mocks/MockTUSD8.sol/MockTUSD8.json" },
] as const;

function main() {
  mkdirSync(OUT_DIR, { recursive: true });

  // 1. Export typed ABIs
  const abiSections: string[] = [
    "// AUTO-GENERATED by scripts/export-abis.ts — DO NOT EDIT MANUALLY",
    "",
  ];

  for (const item of CONTRACT_ARTIFACTS) {
    const fullPath = path.join(ARTIFACTS_DIR, item.relPath);
    if (!existsSync(fullPath)) {
      throw new Error(`Missing compiled artifact: ${fullPath}. Run 'npm run compile' first.`);
    }
    const artifact = JSON.parse(readFileSync(fullPath, "utf-8")) as { abi: unknown[] };
    abiSections.push(`export const ${item.exportName} = ${JSON.stringify(artifact.abi, null, 2)} as const;`);
    abiSections.push("");
  }

  writeFileSync(path.join(OUT_DIR, "abis.ts"), abiSections.join("\n"), "utf-8");

  // 2. Export deployed addresses (falls back to zero addresses until Aevum deploy completes)
  let addresses = {
    tUSD8: DEFAULT_TUSD8,
    IdentityRegistry: ZERO_ADDRESS,
    ReputationRegistry: ZERO_ADDRESS,
    ValidationRegistry: ZERO_ADDRESS,
    MilestoneEscrow: ZERO_ADDRESS,
    ProjectManager: ZERO_ADDRESS,
    DisputeResolution: ZERO_ADDRESS,
  };
  let deployedAt: string | null = null;
  let isDeployed = false;

  if (existsSync(DEPLOYMENTS_FILE)) {
    const manifest = JSON.parse(readFileSync(DEPLOYMENTS_FILE, "utf-8")) as {
      deployedAt?: string;
      contracts?: Partial<typeof addresses>;
    };
    if (manifest.contracts) {
      addresses = { ...addresses, ...manifest.contracts };
      deployedAt = manifest.deployedAt ?? null;
      isDeployed =
        addresses.IdentityRegistry !== ZERO_ADDRESS &&
        addresses.ProjectManager !== ZERO_ADDRESS &&
        addresses.DisputeResolution !== ZERO_ADDRESS;
    }
  }

  const addressesContent = `// AUTO-GENERATED by scripts/export-abis.ts — DO NOT EDIT MANUALLY
import type { Address } from "viem";

export const AEVUM_CHAIN_ID = 44005 as const;
export const AEVUM_EXPLORER_URL = "https://explorer-test.qday.info" as const;
export const TUSD8_DECIMALS = 6 as const;

export const DEPLOYED_AT: string | null = ${JSON.stringify(deployedAt)};
export const IS_PROTOCOL_DEPLOYED: boolean = ${JSON.stringify(isDeployed)};

export const CONTRACT_ADDRESSES: Record<
  | "tUSD8"
  | "IdentityRegistry"
  | "ReputationRegistry"
  | "ValidationRegistry"
  | "MilestoneEscrow"
  | "ProjectManager"
  | "DisputeResolution",
  Address
> = {
  tUSD8: ${JSON.stringify(addresses.tUSD8)},
  IdentityRegistry: ${JSON.stringify(addresses.IdentityRegistry)},
  ReputationRegistry: ${JSON.stringify(addresses.ReputationRegistry)},
  ValidationRegistry: ${JSON.stringify(addresses.ValidationRegistry)},
  MilestoneEscrow: ${JSON.stringify(addresses.MilestoneEscrow)},
  ProjectManager: ${JSON.stringify(addresses.ProjectManager)},
  DisputeResolution: ${JSON.stringify(addresses.DisputeResolution)},
} as const;
`;

  writeFileSync(path.join(OUT_DIR, "addresses.ts"), addressesContent, "utf-8");

  console.log(`Exported ${CONTRACT_ARTIFACTS.length} ABIs and addresses to ${OUT_DIR}`);
  console.log(`Protocol deployed on Aevum: ${isDeployed}`);
}

main();
